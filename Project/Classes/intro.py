import time

def game_intro(user, cat, time_delay):

    print("---------------------------------------------------------------------------------------------------------------------------------")

    print(f"Welcome {user} to Dude Where's my cat!")

    time.sleep(time_delay)

    print("All you want to do is eat some of your favorite chips and watch some TV")

    time.sleep(time_delay)

    print(f"BUT {cat} is missing!")

    time.sleep(time_delay)

    print("You need to find her and get her settled before you can relax.")

    time.sleep(time_delay)

    print("---------------------------------------------------------------------------------------------------------------------------------")